// Builds everything that is made from the logo (`pnpm logo`, rules in brand/README.md):
//   packages/ui/src/logo/data.gen.ts   shapes and strokes for <Logo> and logo.css
//   brand/logo-motion.html             the motion on one page (try it, record it)
//   the app icon as SVG                desktop icon-src, web icon.svg, landing favicon.svg
// and checks that the strokes open the whole logo and that the word's f is the mark's f.
// Sources: fixnote-mark.svg, fixnote-wordmark.svg (the designer's), strokes.json (the pen's way).
import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const brand = dirname(fileURLToPath(import.meta.url))
const root = join(brand, '..')
const read = (name) => readFileSync(join(brand, name), 'utf8')

// ---- sources ----
function source(name, count) {
  const svg = read(name)
  const box = /viewBox="0 0 ([\d.]+) ([\d.]+)"/.exec(svg)
  const paths = [...svg.matchAll(/<path[^>]*\sd="([^"]+)"/g)].map((m) => m[1])
  if (!box || paths.length !== count) {
    throw new Error(
      `${name}: expected a viewBox from 0 0 and ${count} path(s), got ${paths.length}`,
    )
  }
  for (const d of paths) {
    if (/[^MLHVCZ\d\s.,e-]/.test(d)) {
      throw new Error(
        `${name}: only absolute M, L, H, V, C and Z are understood (flatten in Figma)`,
      )
    }
  }
  return { width: Number(box[1]), height: Number(box[2]), paths }
}
const mark = source('fixnote-mark.svg', 1)
const word = source('fixnote-wordmark.svg', 4)
const [wordF, dot, xnot, e] = word.paths
const { scale, strokes: spec } = JSON.parse(read('strokes.json'))

const fmt = (n) => String(Number(n.toFixed(3)))
const scaled = (d, k) => d.replace(/-?\d*\.?\d+(?:e-?\d+)?/g, (n) => fmt(Number(n) * k))
/** The word's f in the mark's coordinates: the two are one shape. */
const f = scaled(wordF, 1 / scale)
const shapes = { f, mark: mark.paths[0], dot, xnot, e }

// ---- stroke lengths: M, L, C, and A used as half ellipses ----
function length(d) {
  const t = d.match(/[MLCA]|-?\d*\.?\d+/g) ?? []
  let at = [0, 0]
  let total = 0
  const dist = (a, b) => Math.hypot(a[0] - b[0], a[1] - b[1])
  for (let i = 0; i < t.length; ) {
    const c = t[i++]
    const n = (k) => t.slice(i, i + k).map(Number)
    if (c === 'M') {
      at = n(2)
      i += 2
    } else if (c === 'L') {
      const p = n(2)
      i += 2
      total += dist(at, p)
      at = p
    } else if (c === 'C') {
      const v = n(6)
      i += 6
      const p = [at, [v[0], v[1]], [v[2], v[3]], [v[4], v[5]]]
      let prev = at
      for (let s = 1; s <= 200; s++) {
        const u = s / 200
        const q = [0, 1].map(
          (j) =>
            (1 - u) ** 3 * p[0][j] +
            3 * (1 - u) ** 2 * u * p[1][j] +
            3 * (1 - u) * u * u * p[2][j] +
            u ** 3 * p[3][j],
        )
        total += dist(prev, q)
        prev = q
      }
      at = p[3]
    } else if (c === 'A') {
      const v = n(7)
      i += 7
      const h = ((v[0] - v[1]) / (v[0] + v[1])) ** 2
      total += (Math.PI * (v[0] + v[1]) * (1 + (3 * h) / (10 + Math.sqrt(4 - 3 * h)))) / 2
      at = [v[5], v[6]]
    } else {
      throw new Error(`strokes.json: unknown path command near "${c}"`)
    }
  }
  return total
}

// ---- strokes: pieces of one line ("chain") share its length, so they move as one ----
const chains = {}
const strokes = spec.map((s) => {
  const d = (s.lead ?? '') + s.d
  const row = {
    id: s.id,
    shape: s.shape,
    space: s.shape === 'f' || s.shape === 'mark' ? 'mark' : 'word',
    d,
    width: s.width,
    length: 1,
    offset: 0,
    block: s.block ?? null,
  }
  if (s.chain) {
    chains[s.chain] ??= { end: 0, rows: [] }
    const chain = chains[s.chain]
    // Where the piece starts on the line: given (`at`), or the lead-in back from the last end.
    const start = s.at ?? chain.end - (s.lead ? length(s.lead) : 0)
    chain.end = start + length(d)
    chain.rows.push([row, start, length(d)])
  }
  return row
})
for (const chain of Object.values(chains)) {
  for (const [row, start, own] of chain.rows) {
    row.length = Number((own / chain.end).toFixed(5))
    row.offset = Number((start / chain.end).toFixed(5))
  }
}
const tail = strokes.find((s) => s.id === 'ta')
/** How far the tail goes back when the mark unfolds: to where it leaves the f. */
const stop = Number((1 - tail.offset).toFixed(5))

const data = {
  scale,
  stop,
  mark: { width: mark.width, height: mark.height },
  word: { width: word.width, height: word.height },
  shapes,
  strokes,
}
writeFileSync(
  join(root, 'packages/ui/src/logo/data.gen.ts'),
  `// Generated by brand/build.mjs (pnpm logo) from brand/. Do not edit.\nexport const logo = ${JSON.stringify(data, null, 2)}\n`,
)

// ---- the same markup <Logo> renders, as a string ----
function markup(id, { live = true } = {}) {
  const mask = (s) =>
    `<mask id="${id}-${s.id}"><path ${
      live
        ? `data-m="${s.id}" pathLength="${s.length}" style="--o:${s.offset}"`
        : 'fill="none" stroke="#fff"'
    } d="${s.d}" stroke-width="${s.width}"/>${s.block ? `<path fill="#000" d="${s.block}"/>` : ''}</mask>`
  const use = (s) => `<use href="#${id}-${s.shape}" mask="url(#${id}-${s.id})"/>`
  const of = (space) =>
    strokes
      .filter((s) => s.space === space)
      .map(use)
      .join('')
  return {
    defs: `<defs>
    <path id="${id}-f" d="${f}"/>
    <path id="${id}-mark" fill-rule="evenodd" d="${shapes.mark}"/>
    <path id="${id}-xnot" fill-rule="evenodd" d="${xnot}"/>
    <path id="${id}-e" fill-rule="evenodd" d="${e}"/>
    ${strokes.map(mask).join('\n    ')}
  </defs>`,
    mark: of('mark'),
    word: of('word'),
  }
}
function logoSvg(id) {
  const m = markup(id)
  return `<svg class="fx-logo" id="${id}" data-phase="word" viewBox="0 0 ${word.width} ${word.height}" role="img" aria-label="FixNote" style="--stop:${stop}">
  ${m.defs}
  <g data-s="lockup">
    <g transform="scale(${scale})">${m.mark}</g>
    <path data-s="dot" d="${dot}"/>
    ${m.word}
  </g>
</svg>`
}
writeFileSync(
  join(brand, 'logo-motion.html'),
  read('motion.template.html')
    .replace('__CSS__', readFileSync(join(root, 'packages/ui/src/logo/logo.css'), 'utf8'))
    .replace('__SHIFT__', fmt((word.width - mark.width * scale) / 2))
    .replace('__MARK_W__', fmt((28 * mark.width * scale) / word.height + 1))
    .replace('__WORD_W__', fmt((28 * word.width) / word.height))
    .replace('__STAGE__', logoSvg('stage'))
    .replace('__INLINE__', logoSvg('small')),
)

// ---- the app icon: an orange tile with continuous corners and the mark in white ----
/** Apple-like corners: a superellipse, not a rectangle with arcs. */
function tile(size) {
  const n = 5
  const h = size / 2
  const points = []
  for (let i = 0; i < 240; i++) {
    const a = (i / 240) * 2 * Math.PI
    const p = (v) => h + h * Math.sign(v) * Math.abs(v) ** (2 / n)
    points.push(`${fmt(p(Math.cos(a)))} ${fmt(p(Math.sin(a)))}`)
  }
  return `M${points.join('L')}Z`
}
function icon({ mac = false, bleed = false, sized = false } = {}) {
  const shape = bleed ? 'M0 0H1024V1024H0Z' : tile(1024)
  // The mark takes 58% of the tile's width (44% when the launcher may crop to a circle).
  const k = ((bleed ? 0.44 : 0.58) * 1024) / mark.width
  const x = (1024 - mark.width * k) / 2
  const y = (1024 - mark.height * k) / 2
  const lift = mac ? 0.8046875 : 1
  return `<svg xmlns="http://www.w3.org/2000/svg" ${sized ? 'width="1024" height="1024" ' : ''}viewBox="0 0 1024 1024"><title>FixNote</title>
  <defs>
    <linearGradient id="bg" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="#ffa565"/>
      <stop offset="0.5" stop-color="#f6742f"/>
      <stop offset="1" stop-color="#e2501a"/>
    </linearGradient>
    <radialGradient id="glow" cx="0.5" cy="0" r="0.85">
      <stop offset="0" stop-color="#fff" stop-opacity="0.3"/>
      <stop offset="0.65" stop-color="#fff" stop-opacity="0"/>
    </radialGradient>
    <linearGradient id="ink" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="#ffffff"/>
      <stop offset="1" stop-color="#ffeadb"/>
    </linearGradient>
    <linearGradient id="rim" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="#fff" stop-opacity="0.38"/>
      <stop offset="0.5" stop-color="#fff" stop-opacity="0.04"/>
      <stop offset="1" stop-color="#5a1800" stop-opacity="0.2"/>
    </linearGradient>
    <clipPath id="tile"><path d="${shape}"/></clipPath>
    <filter id="drop" x="-20%" y="-20%" width="140%" height="150%">
      <feDropShadow dx="0" dy="${fmt(10 / lift)}" stdDeviation="${fmt(14 / lift)}" flood-color="#000" flood-opacity="0.3"/>
    </filter>
    <filter id="lift" x="-30%" y="-30%" width="160%" height="170%">
      <feDropShadow dx="0" dy="${fmt(12 * lift)}" stdDeviation="${fmt(16 * lift)}" flood-color="#8a2a00" flood-opacity="0.34"/>
    </filter>
  </defs>
  <g${mac ? ' transform="translate(100 100) scale(0.8046875)"' : ''}>
    <path d="${shape}" fill="url(#bg)"${mac ? ' filter="url(#drop)"' : ''}/>
    <path d="${shape}" fill="url(#glow)"/>
    ${bleed ? '' : `<path d="${shape}" fill="none" stroke="url(#rim)" stroke-width="10" clip-path="url(#tile)"/>`}
    <g filter="url(#lift)">
      <path transform="translate(${fmt(x)} ${fmt(y)}) scale(${fmt(k)})" fill="url(#ink)" fill-rule="evenodd" d="${shapes.mark}"/>
    </g>
  </g>
</svg>
`
}
writeFileSync(join(root, 'apps/desktop/icon-src/app.svg'), icon({ sized: true }))
writeFileSync(join(root, 'apps/desktop/icon-src/app-macos.svg'), icon({ mac: true, sized: true }))
writeFileSync(join(root, 'apps/web/public/icon.svg'), icon())
writeFileSync(join(root, 'apps/landing/public/favicon.svg'), icon())
writeFileSync(join(brand, 'icon-bleed.svg'), icon({ bleed: true }))

// ---- check: all strokes drawn = the designer's shapes, pixel for pixel ----
let sharp
try {
  sharp = createRequire(join(root, 'apps/desktop/package.json'))('sharp')
} catch {
  console.warn('logo built, not checked: sharp is missing (pnpm install)')
}
if (sharp) {
  const m = markup('c', { live: false })
  const svg = (w, h, body) =>
    Buffer.from(
      `<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" viewBox="-10 -10 ${w + 20} ${h + 20}" width="${(w + 20) * 2}" height="${(h + 20) * 2}"><rect x="-10" y="-10" width="100%" height="100%" fill="#fff"/>${body.replaceAll(' href=', ' xlink:href=')}</svg>`,
    )
  const pairs = {
    mark: [
      svg(mark.width, mark.height, `${m.defs}${m.mark}`),
      svg(mark.width, mark.height, `<path fill-rule="evenodd" d="${shapes.mark}"/>`),
    ],
    word: [
      svg(
        word.width,
        word.height,
        `${m.defs}<g transform="scale(${scale})">${m.mark.split('<use').slice(0, 3).join('<use')}</g><path d="${dot}"/>${m.word}`,
      ),
      svg(
        word.width,
        word.height,
        word.paths.map((d) => `<path fill-rule="evenodd" d="${d}"/>`).join(''),
      ),
    ],
  }
  let failed = false
  for (const [name, [made, wanted]] of Object.entries(pairs)) {
    const [a, b] = await Promise.all(
      [made, wanted].map((s) => sharp(s).greyscale().raw().toBuffer()),
    )
    let off = 0
    for (let i = 0; i < a.length; i++) if (Math.abs(a[i] - b[i]) > 96) off++
    console.log(`${name}: ${off} px differ`)
    if (off > 0) failed = true
  }
  if (failed) {
    console.error('The strokes do not open the logo exactly: fix brand/strokes.json (README).')
    process.exit(1)
  }
}
console.log('logo built')
